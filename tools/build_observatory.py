#!/usr/bin/env python3
"""Build the offline Research Observatory and its Markdown reading edition.

Only the Python standard library is needed. No network requests, inferred
evidence states, current-time stamps, or third-party frontend dependencies.
Run with --check to verify every generated byte and the input/output hashes.
"""

from __future__ import annotations

import argparse
import hashlib
import html
import json
import re
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parent.parent
SOURCE = "https://github.com/topherchris420/topherchris420/blob/main/"
INPUTS = (
    "docs/atlas.json", "experiments/ledger.json", "tools/build_observatory.py",
    "tools/observatory.html", "tools/observatory.css", "tools/observatory.js",
)


def digest(content: bytes) -> str:
    return hashlib.sha256(content).hexdigest()


def safe_url(url: str) -> str:
    """Allow external HTTPS links only, including from future catalog edits."""
    parsed = urlsplit(url)
    if (parsed.scheme != "https" or not parsed.netloc or parsed.username
            or parsed.password or any(ord(c) < 33 for c in url)
            or any(c in url for c in '<>"\\')):
        raise ValueError(f"Expected a public HTTPS URL: {url!r}")
    return url


def canonical(url: str) -> str:
    return safe_url(url).rstrip("/").removesuffix(".git").casefold()


def script_json(data: dict) -> str:
    # A JSON script element still obeys HTML's closing-tag parser.
    return json.dumps(data, ensure_ascii=True, separators=(",", ":")).replace(
        "<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")


def build_data(atlas: dict, ledger: dict) -> dict:
    from build_atlas import validate
    from check_profile import Report, check_ledger

    problems = validate(atlas)
    report = Report()
    check_ledger(ledger, report)
    problems.extend(report.failures)
    if problems:
        raise ValueError("\n".join(problems))

    by_url = {}
    for entry in ledger["experiments"]:
        key = canonical(entry["repo"])
        if key in by_url:
            raise ValueError(f"Ambiguous ledger repository: {key}")
        by_url[key] = entry
    records, used, ids = [], set(), set()
    gone = {name.casefold() for name in atlas.get("no_longer_public", [])}

    def add(project: dict | None, entry: dict | None) -> None:
        project = project or {}
        entry = entry or {}
        source = (f"https://github.com/{atlas['owner']}/{project['repo']}"
                  if project.get("repo") else project.get("url") or entry["repo"])
        ident = entry.get("id") or "catalog-" + re.sub(
            r"[^a-z0-9]+", "-", (project.get("repo") or project["name"]).lower()).strip("-")
        if ident in ids:
            raise ValueError(f"Duplicate observatory id: {ident}")
        ids.add(ident)
        links = [{"label": "Project source" if project.get("repo") else "Project", "url": source}]
        if project.get("url") and canonical(project["url"]) != canonical(source):
            links.append({"label": project.get("url_label", "Open project"), "url": project["url"]})
        links += project.get("links", [])
        for link in links:
            safe_url(link["url"])
        for url in [*(link["url"] for link in links), *entry.get("evidence", [])]:
            safe_url(url)
            parsed = urlsplit(url)
            parts = parsed.path.strip("/").split("/")
            if (parsed.hostname in ("github.com", "raw.githubusercontent.com") and len(parts) >= 2
                    and parts[0].casefold() == atlas["owner"].casefold() and parts[1].casefold() in gone):
                raise ValueError(f"Non-public repository in observatory: {url}")
        records.append({
            "id": ident, "name": project.get("name") or entry["name"],
            "description": project.get("description", entry.get("question", "")),
            "do": project.get("do", "Inspect the recorded scope and linked source."),
            "theme": project.get("theme", "explore-a-research-lab"),
            "status": project.get("status", "active"), "maturity": project.get("maturity", "Recorded experiment"),
            "links": links, "source_note": project.get("source_note", ""),
            "catalog_reviewed": project.get("last_reviewed", atlas["reviewed"]),
            "ledger": entry or None,
        })

    for project in atlas["projects"]:
        source = (f"https://github.com/{atlas['owner']}/{project['repo']}"
                  if project.get("repo") else project["url"])
        entry = by_url.get(canonical(source))
        if entry:
            used.add(entry["id"])
        add(project, entry)
    for entry in ledger["experiments"]:
        if entry["id"] not in used:
            add(None, entry)
    return {
        "schema": "vers3dynamics-observatory/v1", "atlas_reviewed": atlas["reviewed"],
        "ledger_reviewed": ledger["reviewed"], "coverage_checked": atlas.get("coverage_checked"),
        "note": ledger["note"], "questions": ledger["questions"], "states": ledger["states"],
        "themes": atlas["themes"], "records": records,
    }


def esc(value: str) -> str:
    return html.escape(value, quote=True)


def cards(data: dict) -> str:
    """Full reading experience before JavaScript (progressive enhancement)."""
    out = []
    for r in data["records"]:
        e = r["ledger"]
        states = e["state"] if e else []
        scopes = "".join(f'<li><strong>{esc(s["state"])}</strong> — {esc(s["scope"])}</li>' for s in states)
        sources = "".join(f'<li><a href="{esc(url)}">{esc(url)}</a></li>' for url in (e or {}).get("evidence", []))
        links = " · ".join(f'<a href="{esc(link["url"])}">{esc(link["label"])}</a>' for link in r["links"])
        reviewed = e.get("last_reviewed", data["ledger_reviewed"]) if e else r["catalog_reviewed"]
        state_labels = " · ".join(s["state"] for s in states) or "NO LEDGER ENTRY"
        detail = (f'<p class="question">{esc(e["question"])}</p><ul class="scopes">{scopes}</ul>'
                  f'<h4>Still open</h4><p>{esc(e.get("open", "No separate limitation recorded; read each state’s scope."))}</p>'
                  f'<h4>Next experiment</h4><p>{esc(e.get("next", "No next experiment recorded."))}</p>'
                  f'<h4>Source records</h4><ul class="sources">{sources}</ul>' if e else
                  '<p>This project has no evidence-ledger entry. Its catalog maturity is not an evidence verdict.</p>')
        visibility = f'<p>{esc(e["visibility"])}</p>' if e and e.get("visibility") else ""
        out.append(f'''<article class="record" id="{esc(r['id'])}" data-record="{esc(r['id'])}">
<div class="record-meta"><span>{esc(r['maturity'])} · {esc(r['status'])}</span><span>{'Evidence' if e else 'Catalog'} review · {reviewed}</span></div>
<div class="record-heading"><h3><a href="{esc(r['links'][0]['url'])}">{esc(r['name'])}</a></h3><label class="compare-control" hidden><input type="checkbox" value="{esc(r['id'])}" aria-label="Compare {esc(r['name'])}"> Compare</label></div>
<p>{esc(r['description'])}</p><p class="invitation">{esc(r['do'])}.</p>
<p class="state-line">{esc(state_labels)}</p>
<details><summary>Evidence, limits &amp; next experiment</summary>{detail}{visibility}</details>
<div class="record-links">{links} · <a class="permalink" href="#{esc(r['id'])}">Permalink</a></div>
{'<p class="source-note">'+esc(r['source_note'])+'</p>' if r['source_note'] else ''}
</article>''')
    return "\n".join(out)


def markdown(data: dict) -> str:
    lines = ["# Research Observatory", "",
             "[← Profile](../README.md) · [Project atlas](atlas.md) · [Evidence definitions](../experiments/README.md#the-evidence-ladder)", "",
             "**What would change our minds?** A reading edition generated from the evidence ledger. Every scope, limitation and next experiment below comes from its recorded entry. The interactive edition also includes projects with no ledger entry.", "",
             "[**Download the interactive observatory**](https://raw.githubusercontent.com/topherchris420/topherchris420/main/docs/observatory.html) · [View its file](observatory.html)", "",
             "Save the linked file as `observatory.html` and open it in a browser. It works offline: search, filter by question or evidence state, compare up to three projects, export the visible records, or print a comparison. No account, server or package installation is needed. External source links need a connection.", "",
             f"Latest evidence review: **{data['ledger_reviewed']}**. This was a partial review; each entry retains its own date. A software build does not refresh those dates or establish independent reproduction.", "",
             "<!-- Generated by tools/build_observatory.py. Edit the ledger, not this page. -->", ""]
    for question in data["questions"].values():
        lines += [f"## {question}", ""]
        for r in data["records"]:
            e = r["ledger"]
            if not e or e["question"] != question:
                continue
            lines += [f"### {e['name']}", "", f"[Project]({e['repo']}) · Reviewed {e.get('last_reviewed', data['ledger_reviewed'])}", ""]
            for s in e["state"]:
                lines += [f"- **`{s['state']}`** — {s['scope']}"]
            lines += ["", f"**Still open:** {e.get('open', 'No separate limitation recorded; read each state’s scope.')}", "",
                      f"**Next experiment:** {e.get('next', 'No next experiment recorded.')}", ""]
            if e.get("visibility"):
                lines += [e["visibility"], ""]
            sources = e.get("evidence", [])
            if sources:
                lines += ["**Source records:** " + " · ".join(f"[{i + 1}]({url})" for i, url in enumerate(sources)), ""]
    return "\n".join(lines).rstrip() + "\n"


def outputs(root: Path = ROOT) -> dict[str, bytes]:
    atlas = json.loads((root / "docs/atlas.json").read_text(encoding="utf-8"))
    ledger = json.loads((root / "experiments/ledger.json").read_text(encoding="utf-8"))
    data = build_data(atlas, ledger)
    inputs = {name: digest((root / name).read_bytes()) for name in INPUTS}
    data["inputs"] = inputs
    summary = {
        "projects": len(data["records"]), "records": sum(bool(r["ledger"]) for r in data["records"]),
        "negative": sum(any(s["state"] == "NOT SUPPORTED" for s in (r["ledger"] or {}).get("state", [])) for r in data["records"]),
        "reproduced": sum(any(s["state"] == "REPRODUCED" for s in (r["ledger"] or {}).get("state", [])) for r in data["records"]),
    }
    template = (root / "tools/observatory.html").read_text(encoding="utf-8")
    replacements = {
        "CSS": (root / "tools/observatory.css").read_text(encoding="utf-8"),
        "JS": (root / "tools/observatory.js").read_text(encoding="utf-8"),
        "DATA": script_json(data), "CARDS": cards(data), "REVIEWED": data["ledger_reviewed"],
        "QUESTIONS": "".join(f'<option value="{esc(k)}">{esc(v)}</option>' for k, v in data["questions"].items()),
        "STATES": "".join(f'<option value="{esc(k)}">{esc(k)}</option>' for k in data["states"]),
        "THEMES": "".join(f'<option value="{esc(t["id"])}">{esc(t["title"])}</option>' for t in data["themes"]),
        "DEFINITIONS": "".join(f'<dt>{esc(k)}</dt><dd>{esc(v)}</dd>' for k, v in data["states"].items()),
        "HASHES": "".join(f'<li><a href="{SOURCE+name}">{name}</a><code>{sha}</code></li>' for name, sha in inputs.items()),
        **{k.upper(): str(v) for k, v in summary.items()},
    }
    # A single substitution pass prevents inserted user text being interpreted as a template.
    rendered = re.sub(r"@@([A-Z]+)@@", lambda m: replacements[m[1]], template)
    files = {"docs/observatory.html": rendered.encode(), "docs/research.md": markdown(data).encode()}
    manifest = {"schema": "vers3dynamics-observatory-build/v1", "inputs": inputs,
                "outputs": {name: digest(content) for name, content in files.items()}}
    files["docs/observatory-manifest.json"] = (json.dumps(manifest, indent=2) + "\n").encode()
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        files = outputs()
    except (ValueError, KeyError, TypeError) as exc:
        parser.exit(1, f"Invalid observatory input: {exc}\n")
    stale = []
    for name, content in files.items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_bytes() != content:
                stale.append(name)
        else:
            path.write_bytes(content)
    if stale:
        print("Stale observatory output: " + ", ".join(stale))
        print("Run python3 tools/build_observatory.py")
        return 1
    print(f"Observatory: {len(files)} {'verified' if args.check else 'generated'} files; offline and deterministic.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
